val JetBrainsMonoFamily = FontFamily(
    Font(R.font.jetbrains_mono, FontWeight.Normal),
    Font(R.font.jetbrains_mono, FontWeight.Medium),
    Font(R.font.jetbrains_mono, FontWeight.Bold)
)

val InterFamily = FontFamily(
    Font(R.font.inter, FontWeight.Normal),
    Font(R.font.inter, FontWeight.Medium),
    Font(R.font.inter, FontWeight.SemiBold),
    Font(R.font.inter, FontWeight.Bold)
)

fun terminalComposeFontFamily(fontId: String?): FontFamily =
    when (com.example.terminal.TerminalFontRegistry.fromId(fontId).id) {
        com.example.terminal.TerminalFontRegistry.SYSTEM_MONOSPACE_ID -> FontFamily.Monospace
        else -> JetBrainsMonoFamily
    }

